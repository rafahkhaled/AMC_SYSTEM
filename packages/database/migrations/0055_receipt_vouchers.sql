/*
 * A receipt voucher for every payment, numbered like the firm's paper ones.
 *
 * The firm hands a client a "RECEIVE VOUCHER" (سند قبض) for money received,
 * numbered `2026/1933`: the year, then a running number that does not restart.
 * The number is the database's, not the application's, so two payments
 * recorded at the same moment can never share one. It carries on from where
 * the paper book stopped.
 */
ALTER TABLE payments
  ADD COLUMN voucher_number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1934);

CREATE UNIQUE INDEX payments_voucher_number ON payments (voucher_number);
